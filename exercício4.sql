-- Exercício 4, letra A

--
CLIENTES      (ID, NOME) 
PEDIDOS       (ID, ID_CLIENTE, DATA, SITUACAO) 
ITENS_PEDIDO  (ID, ID_PEDIDO, SKU, QTD, VALOR_UNIT)
--

SELECT
    CLI.NOME,
    PED.ID AS ID_PEDIDO,
    SUM(ITEM.QTD * ITEM.VALOR_UNIT) AS VALOR_TOTAL
FROM CLIENTES CLI
JOIN PEDIDOS PED
    ON CLI.ID = PED.ID_CLIENTE
JOIN ITENS_PEDIDO ITEM
    ON PED.ID = ITEM.ID_PEDIDO
WHERE PED.SITUACAO = 'Faturado'
GROUP BY CLI.NOME, PED.ID;

-- Exercício 4, letra B
SELECT
    PED.ID
FROM PEDIDOS PED
LEFT JOIN ITENS_PEDIDO ITEM
    ON PED.ID = ITEM.ID_PEDIDO
WHERE ITEM.ID_PEDIDO IS NULL;

